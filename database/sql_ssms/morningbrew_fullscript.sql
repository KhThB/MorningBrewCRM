      OrderCode=CONCAT('MB',FORMAT(DATEADD(hour,7,@hAt),'yyMMdd'),'-',CASE WHEN @hOrder>9999 THEN CONVERT(varchar(12),@hOrder) ELSE RIGHT(CONCAT('0000',@hOrder),4) END)
