DECLARE @r TABLE(ID int);
DECLARE @voucher int,@order int,@payment int,@refund int,@key uniqueidentifier=NEWID();
INSERT @r EXEC dbo.IssueVoucher 5,1,1,@key;
SELECT @voucher=ID FROM @r; DELETE @r;
SET @key=NEWID();
INSERT @r EXEC dbo.CreateOrder @ActorID=5,@BranchID=1,@Source='App',@Fulfillment='Pickup',@PaymentMode='Prepaid',@Items=N'[{"variantId":1,"quantity":2,"optionIds":[1,3,5]}]',@RequestKey=@key,@CustomerID=1,@CustomerPromotionID=@voucher;
