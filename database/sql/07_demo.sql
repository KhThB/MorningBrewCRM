EXEC dbo.AdvanceOrder 4,@order,'Confirmed'; EXEC dbo.AdvanceOrder 4,@order,'Preparing'; EXEC dbo.AdvanceOrder 4,@order,'Ready'; EXEC dbo.AdvanceOrder 4,@order,'Completed';
